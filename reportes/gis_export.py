"""GIS exports — KML (Google Earth), CSV con coords, GeoJSON.

Cierra gap crítico vs WindPRO/OpenWind (que exportan SHP/DXF/KML nativamente).
Formatos open-source preferidos:
  - KML: simplekml (puro Python, no dep pesadas)
  - GeoJSON: pure dict + json (estándar web)
  - CSV con coords: para import a GIS / Excel
"""

from __future__ import annotations

import io
import json

import pandas as pd


def turbinas_xy_a_latlon_simple(df_layout, lat_centro, lon_centro):
    """Conversión x_m/y_m → lat/lon. Aprox planar."""
    import math
    lat0 = float(lat_centro)
    lon0 = float(lon_centro)
    m_per_deg_lat = 111000.0
    m_per_deg_lon = 111000.0 * math.cos(math.radians(lat0))
    if m_per_deg_lon <= 0:
        m_per_deg_lon = 111000.0
    out = df_layout.copy()
    out["lat"] = lat0 + pd.to_numeric(out.get("y_m", 0), errors="coerce") / m_per_deg_lat
    out["lon"] = lon0 + pd.to_numeric(out.get("x_m", 0), errors="coerce") / m_per_deg_lon
    return out


def _kml_escape(s: str) -> str:
    return (str(s)
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;"))


def exportar_kml_layout(
    df_layout, lat_centro, lon_centro,
    nombre_parque="Wind Farm", diametro_rotor=100, altura_buje=80,
    receptores_flicker=None, receptores_ruido=None,
    polygon_concesion_xy=None,
):
    """Genera KML para Google Earth/Maps con:
      - Pin centro del parque
      - Pins turbinas con popup (id, lat/lon, altura)
      - Línea conectando turbinas (visual layout)
      - Receptores flicker (amarillo) y ruido (rojo) opcional
      - Polygon concesión opcional

    Styles are defined at Document level so Google Earth Web resolves them.
    Returns: bytes del KML.
    """
    # KML colors: aabbggrr (alpha, blue, green, red)
    PURPLE  = "ffff0078"  # purple pushpin
    BLUE    = "ffff0000"  # blue (KML ABGR: ff=opaque, 00=red, 00=green, ff=blue)
    GREEN   = "ff00ff00"
    YELLOW  = "ff00ffff"
    RED     = "ff0000ff"

    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<kml xmlns="http://www.opengis.net/kml/2.2">',
        '<Document>',
        f'  <name>{_kml_escape(nombre_parque)}</name>',
        f'  <description>Wind farm: {_kml_escape(nombre_parque)}\n'
        f'Center: {lat_centro:.6f}, {lon_centro:.6f}\n'
        f'Rotor diameter: {diametro_rotor} m\n'
        f'Hub height: {altura_buje} m\n'
        f'Generated by SMA 2.0</description>',
        # --- Document-level shared styles ---
        '  <Style id="style_center">',
        '    <IconStyle>',
        f'      <color>{PURPLE}</color>',
        '      <scale>1</scale>',
        '    </IconStyle>',
        '  </Style>',
        '  <Style id="style_turbine">',
        '    <IconStyle>',
        f'      <color>{BLUE}</color>',
        '      <scale>1.0</scale>',
        '    </IconStyle>',
        '  </Style>',
        '  <Style id="style_layout_line">',
        '    <LineStyle>',
        f'      <color>{GREEN}</color>',
        '      <width>2</width>',
        '    </LineStyle>',
        '  </Style>',
        '  <Style id="style_flicker">',
        '    <IconStyle>',
        f'      <color>{YELLOW}</color>',
        '      <scale>1.0</scale>',
        '    </IconStyle>',
        '  </Style>',
        '  <Style id="style_noise">',
        '    <IconStyle>',
        f'      <color>{RED}</color>',
        '      <scale>1.0</scale>',
        '    </IconStyle>',
        '  </Style>',
        '  <Style id="style_concession">',
        '    <LineStyle>',
        f'      <color>{YELLOW}</color>',
        '      <width>2</width>',
        '    </LineStyle>',
        '    <PolyStyle>',
        '      <color>3200ffff</color>',
        '    </PolyStyle>',
        '  </Style>',
        # --- Site center placemark ---
        '  <Placemark>',
        '    <name>Site Center</name>',
        f'    <description>Site reference point\nLat: {lat_centro}\nLon: {lon_centro}</description>',
        '    <styleUrl>#style_center</styleUrl>',
        '    <Point>',
        f'      <coordinates>{lon_centro},{lat_centro},0</coordinates>',
        '    </Point>',
        '  </Placemark>',
    ]

    # --- Turbines folder ---
    df_ll = turbinas_xy_a_latlon_simple(df_layout, lat_centro, lon_centro)
    lines.append('  <Folder>')
    lines.append('    <name>Turbines</name>')
    coords_line = []
    for _, row in df_ll.iterrows():
        tid = str(row.get("turbina_id", "T?"))
        lat_t = float(row["lat"])
        lon_t = float(row["lon"])
        desc = (f"Turbine ID: {_kml_escape(tid)}\nLat: {lat_t:.6f}\nLon: {lon_t:.6f}\n"
                f"Hub height: {altura_buje} m\nRotor: {diametro_rotor} m")
        lines += [
            '    <Placemark>',
            f'      <name>{_kml_escape(tid)}</name>',
            f'      <description>{desc}</description>',
            '      <styleUrl>#style_turbine</styleUrl>',
            '      <Point>',
            f'        <coordinates>{lon_t},{lat_t},0</coordinates>',
            '      </Point>',
            '    </Placemark>',
        ]
        coords_line.append((lon_t, lat_t))

    if len(coords_line) >= 2:
        coord_str = " ".join(f"{lon},{lat},0" for lon, lat in coords_line)
        lines += [
            '    <Placemark>',
            '      <name>Layout connection</name>',
            '      <styleUrl>#style_layout_line</styleUrl>',
            '      <LineString>',
            f'        <coordinates>{coord_str}</coordinates>',
            '      </LineString>',
            '    </Placemark>',
        ]
    lines.append('  </Folder>')

    # --- Concession polygon ---
    if polygon_concesion_xy and len(polygon_concesion_xy) >= 3:
        poly_coords = []
        for x, y in polygon_concesion_xy:
            df_poly = pd.DataFrame({"turbina_id": ["P"], "x_m": [x], "y_m": [y]})
            df_poly_ll = turbinas_xy_a_latlon_simple(df_poly, lat_centro, lon_centro)
            poly_coords.append((float(df_poly_ll.iloc[0]["lon"]), float(df_poly_ll.iloc[0]["lat"])))
        poly_coords.append(poly_coords[0])
        coord_str = " ".join(f"{lon},{lat},0" for lon, lat in poly_coords)
        lines += [
            '  <Placemark>',
            '    <name>Concession area</name>',
            '    <styleUrl>#style_concession</styleUrl>',
            '    <Polygon>',
            '      <outerBoundaryIs><LinearRing>',
            f'        <coordinates>{coord_str}</coordinates>',
            '      </LinearRing></outerBoundaryIs>',
            '    </Polygon>',
            '  </Placemark>',
        ]

    # --- Flicker receptors ---
    if receptores_flicker:
        lines.append('  <Folder>')
        lines.append('    <name>Shadow flicker receptors</name>')
        for rec in receptores_flicker:
            rid = rec.get("receptor_id", "R?")
            df_rec = pd.DataFrame({"turbina_id": [rid], "x_m": [rec.get("x_m", 0)], "y_m": [rec.get("y_m", 0)]})
            df_rec_ll = turbinas_xy_a_latlon_simple(df_rec, lat_centro, lon_centro)
            lat_r = float(df_rec_ll.iloc[0]["lat"])
            lon_r = float(df_rec_ll.iloc[0]["lon"])
            nombre = rec.get("nombre", rid)
            horas = rec.get("horas_flicker_anuales", "N/D")
            lines += [
                '    <Placemark>',
                f'      <name>Flicker: {_kml_escape(nombre)}</name>',
                f'      <description>Receptor: {_kml_escape(nombre)}\nFlicker hours/year: {horas}</description>',
                '      <styleUrl>#style_flicker</styleUrl>',
                '      <Point>',
                f'        <coordinates>{lon_r},{lat_r},0</coordinates>',
                '      </Point>',
                '    </Placemark>',
            ]
        lines.append('  </Folder>')

    # --- Noise receptors ---
    if receptores_ruido:
        lines.append('  <Folder>')
        lines.append('    <name>Noise receptors</name>')
        for rec in receptores_ruido:
            rid = rec.get("receptor_id", "R?")
            df_rec = pd.DataFrame({"turbina_id": [rid], "x_m": [rec.get("x_m", 0)], "y_m": [rec.get("y_m", 0)]})
            df_rec_ll = turbinas_xy_a_latlon_simple(df_rec, lat_centro, lon_centro)
            lat_r = float(df_rec_ll.iloc[0]["lat"])
            lon_r = float(df_rec_ll.iloc[0]["lon"])
            nombre = rec.get("nombre", rid)
            lpA = rec.get("lpA_db", "N/D")
            lines += [
                '    <Placemark>',
                f'      <name>Noise: {_kml_escape(nombre)}</name>',
                f'      <description>Receptor: {_kml_escape(nombre)}\nLpA: {lpA} dB(A)</description>',
                '      <styleUrl>#style_noise</styleUrl>',
                '      <Point>',
                f'        <coordinates>{lon_r},{lat_r},0</coordinates>',
                '      </Point>',
                '    </Placemark>',
            ]
        lines.append('  </Folder>')

    lines += ['</Document>', '</kml>']
    return "\n".join(lines).encode("utf-8")


def exportar_geojson_layout(df_layout, lat_centro, lon_centro,
                            nombre_parque="WindFarm", metadata=None):
    """Genera GeoJSON FeatureCollection — estándar web/GIS."""
    df_ll = turbinas_xy_a_latlon_simple(df_layout, lat_centro, lon_centro)
    features = []
    # Centro del sitio
    features.append({
        "type": "Feature",
        "geometry": {"type": "Point", "coordinates": [float(lon_centro), float(lat_centro)]},
        "properties": {"name": f"{nombre_parque} center", "type": "site_center"},
    })
    for _, row in df_ll.iterrows():
        tid = str(row.get("turbina_id", "T?"))
        lon_t = float(row["lon"])
        lat_t = float(row["lat"])
        features.append({
            "type": "Feature",
            "geometry": {"type": "Point", "coordinates": [lon_t, lat_t]},
            "properties": {
                "name": tid, "type": "turbine",
                "x_m": float(row.get("x_m", 0)),
                "y_m": float(row.get("y_m", 0)),
            },
        })
    payload = {
        "type": "FeatureCollection",
        "name": nombre_parque,
        "metadata": metadata or {},
        "features": features,
    }
    return json.dumps(payload, indent=2, ensure_ascii=False).encode("utf-8")


def exportar_csv_coords(df_layout, lat_centro, lon_centro, separador=","):
    """CSV con coords WGS84 — formato universal para import GIS/Excel/QGIS."""
    df_ll = turbinas_xy_a_latlon_simple(df_layout, lat_centro, lon_centro)
    cols = ["turbina_id", "lat", "lon", "x_m", "y_m"]
    cols_present = [c for c in cols if c in df_ll.columns]
    csv_str = df_ll[cols_present].to_csv(index=False, sep=separador)
    return csv_str.encode("utf-8")


def exportar_zip_paquete_gis(df_layout, lat_centro, lon_centro, nombre_parque="WindFarm", **kwargs):
    """ZIP con KML + GeoJSON + CSV — paquete GIS completo para descarga."""
    import zipfile
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"{nombre_parque}.kml", exportar_kml_layout(df_layout, lat_centro, lon_centro, nombre_parque=nombre_parque, **kwargs))
        zf.writestr(f"{nombre_parque}.geojson", exportar_geojson_layout(df_layout, lat_centro, lon_centro, nombre_parque=nombre_parque))
        zf.writestr(f"{nombre_parque}_coords.csv", exportar_csv_coords(df_layout, lat_centro, lon_centro))
    buffer.seek(0)
    return buffer.read()
